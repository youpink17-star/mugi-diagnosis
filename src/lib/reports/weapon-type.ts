export function buildWeaponTypeResult(
  scores: Record<string, number>,
  segment: Segment = "offline",
  stage?: string
): FreeResult {
  const top =
    [...ORDER].sort((a, b) => (scores[b] ?? 0) - (scores[a] ?? 0))[0] ?? "inventor";
  const id = IDENTITY[top];
  const pt = PROFILE_TYPES[top as keyof typeof PROFILE_TYPES];
  const seg = (SEG_DATA[segment] ?? OFFLINE)[top];
  const meta = SEG_META[segment] ?? SEG_META.offline;
  const intro = STAGE_INTRO[stage ?? "started"] ?? STAGE_INTRO.started;

  const sections: ReportSection[] = [
    {
      icon: "✨",
      heading: "이런 사람이에요",
      body: `${id.oneLine}\n\n${id.weakness}`,
    },
    {
      icon: "🔎",
      heading: "이런 특징이 있어요",
      bullets: pt.traits,
    },
    {
      icon: "🗡️",
      heading: "내 핵심 무기",
      chips: pt.strengths,
    },
    {
      icon: "⚔️",
      heading: "너의 차별화 포인트",
      body: id.diff,
    },
    {
      icon: "⚠️",
      heading: "이런 함정에 빠지기 쉬워요",
      bullets: pt.failurePatterns,
    },
    {
      icon: "💰",
      heading: "나의 돈 버는 루트",
      highlight: seg.moneyRoute,
    },
    {
      icon: "🎁",
      heading: "그래서 너한텐 이게 맞아",
      bullets: seg.itemRec,
    },
    {
      icon: "📌",
      heading: "같은 결의 브랜드",
      examples: [{ name: seg.exName, desc: seg.exBody }],
    },
    {
      icon: "🌈",
      heading: "가볍게 시작한다면",
      body: seg.firstStep,
    },
    {
      icon: "🧰",
      heading: "무기제작소에서 이어서",
      body: `여기서 끝이 아니에요. 무기제작소(무기지도)의 **‘${meta.workshop}’**에 이 결과를 옮겨두면, 네 무기 유형에 맞는 다음 할 일과 템플릿이 차곡차곡 쌓여요. 진단은 시작이고, 진짜는 작업실에서 굴러가요.`,
    },
  ];

  return {
    typeName: id.king,
    typeEmoji: pt.emoji,
    tagline: pt.oneLine,
    summary: intro,
    sections,
    scores,
  };
}
