const STATE_INTRO: Record<string, string> = {
  none: "팔 게 없는 게 아니라, 아직 안 고른 것뿐이에요. 당신 안엔 이미 무기가 있어요.",
  many: "재능이 없어서가 아니라, 너무 많아서 못 고르는 거예요. 그중 하나만 같이 골라봐요.",
  doubt: "이게 될지 의심된다면 — 아이템이 문제가 아니라 ‘내 무기와 맞는지’부터 보면 돼요.",
};

export function buildFindItemResult(
  scores: Record<string, number>,
  state?: string
): FreeResult {
  const top =
    [...ORDER].sort((a, b) => (scores[b] ?? 0) - (scores[a] ?? 0))[0] ?? "inventor";
  const t = TYPES[top];
  const pt = PROFILE_TYPES[top as keyof typeof PROFILE_TYPES];
  const intro = STATE_INTRO[state ?? "none"] ?? STATE_INTRO.none;

  const sections: ReportSection[] = [
    {
      icon: "✨",
      heading: "이런 사람이에요",
      body: `${t.oneLine}\n\n${t.weakness}`,
    },
    {
      icon: "🔎",
      heading: "이런 특징이 있어요",
      bullets: pt.traits,
    },
    {
      icon: "🗡️",
      heading: "내 핵심 무기",
      chips: pt.strengths,
    },
    {
      icon: "⚠️",
      heading: "이런 함정에 빠지기 쉬워요",
      bullets: pt.failurePatterns,
    },
    {
      icon: "💰",
      heading: "나의 돈 버는 루트",
      highlight: pt.moneyRoute,
    },
    {
      icon: "🎁",
      heading: "그래서 너한텐 이런 게 맞아",
      bullets: t.itemRec,
    },
    {
      icon: "📌",
      heading: "같은 결의 브랜드",
      examples: [{ name: t.exName, desc: t.exBody }],
    },
    {
      icon: "🌈",
      heading: "가볍게 시작한다면",
      body: t.firstStep,
    },
  ];

  return {
    typeName: t.king,
    typeEmoji: pt.emoji,
    tagline: pt.oneLine,
    summary: intro,
    sections,
    scores,
  };
}
