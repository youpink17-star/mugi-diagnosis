const STATE_INTRO: Record<string, string> = {
  crowded: "비슷한 가게가 많은 게 문제가 아니에요. 아직 ‘내 한 곳’을 안 정했을 뿐이에요. 같이 찾아봐요.",
  blank: "차별점이 없는 게 아니라, 아직 안 꺼낸 거예요. 당신한텐 이미 남다른 무기가 있어요.",
  untold: "다른 점은 분명 있어요. 손님한테 ‘보여주는 법’만 같이 손보면 돼요.",
};

export function buildDifferentiationResult(
  scores: Record<string, number>,
  state?: string
): FreeResult {
  const top =
    [...ORDER].sort((a, b) => (scores[b] ?? 0) - (scores[a] ?? 0))[0] ?? "niche";
  const t = TYPES[top];
  const intro = STATE_INTRO[state ?? "crowded"] ?? STATE_INTRO.crowded;

  const sections: ReportSection[] = [
    {
      icon: "✨",
      heading: "이런 사람이에요",
      body: `${t.oneLine}\n\n${t.weakness}`,
    },
    {
      icon: "🔎",
      heading: "이런 특징이 있어요",
      bullets: t.traits,
    },
    {
      icon: "🗡️",
      heading: "내 차별화 무기",
      chips: t.strengths,
    },
    {
      icon: "⚠️",
      heading: "이런 함정에 빠지기 쉬워요",
      bullets: t.failurePatterns,
    },
    {
      icon: "💰",
      heading: "이 차별화로 돈 버는 길",
      highlight: t.moneyRoute,
    },
    {
      icon: "🎁",
      heading: "그래서 너한텐 이게 맞아",
      bullets: t.itemRec,
    },
    {
      icon: "📌",
      heading: "같은 결의 브랜드",
      examples: [{ name: t.exName, desc: t.exBody }],
    },
    {
      icon: "🌈",
      heading: "가볍게 시작한다면",
      body: t.firstStep,
    },
  ];

  return {
    typeName: t.king,
    typeEmoji: t.emoji,
    tagline: t.tagline,
    summary: intro,
    sections,
    scores,
  };
}
