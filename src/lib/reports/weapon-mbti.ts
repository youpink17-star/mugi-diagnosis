// 축 점수 → 3글자 코드.
// 두 쪽 점수가 같으면 "전혀/매우"로 더 강하게 답한 쪽(x 점수)을 고르고, 그것도 같을 때만 앞 글자(E/R/N).
// 세 축이 전부 같은 경우(전부 "보통" 등)는 테스트 화면에서 제출 전에 다시 골라달라고 안내한다.
export const WEAPON_AXES: [string, string][] = [["E", "S"], ["R", "I"], ["N", "P"]];
export function deriveWeaponCode(raw: Record<string, number>): string {
  const g = (k: string) => raw[k] ?? 0;
  return WEAPON_AXES.map(([l, r]) => {
    if (g(l) !== g(r)) return g(l) > g(r) ? l : r;
    return g(`${r}x`) > g(`${l}x`) ? r : l;
  }).join("");
}

// 세 축 모두 한쪽으로 기울지 않았는지 (유형을 가릴 근거가 없는 답)
export function isUndecided(raw: Record<string, number>): boolean {
  const g = (k: string) => raw[k] ?? 0;
  return WEAPON_AXES.every(([l, r]) => g(l) === g(r) && g(`${l}x`) === g(`${r}x`));
}

